CREATE TABLE fp.merchant_monthly_stats (
  merchant_id       uuid NOT NULL REFERENCES fp.merchants,
  month             date NOT NULL CHECK (extract(day FROM month) = 1),
  tx_count          integer NOT NULL DEFAULT 0 CHECK (tx_count >= 0),
  gross             numeric(14,2) NOT NULL DEFAULT 0 CHECK (gross >= 0),
  rebate_journal_id uuid UNIQUE REFERENCES fp.journals,
  PRIMARY KEY (merchant_id, month)
);

-- ── Tamper-evident audit log (hash chain) and rate limits ─────────────────────────────────
CREATE TABLE fp.audit_log (
  seq         bigint PRIMARY KEY,
  occurred_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  actor_type  text NOT NULL CHECK (actor_type IN ('STAFF','TERMINAL','SYSTEM','CUSTOMER_SMS')),
  actor_id    text NOT NULL CHECK (length(actor_id) BETWEEN 1 AND 120),
  action      text NOT NULL CHECK (action ~ '^[a-z_]+\.[a-z_]+$'),
  entity_type text NOT NULL CHECK (length(entity_type) BETWEEN 1 AND 40),
  entity_id   text NOT NULL CHECK (length(entity_id) BETWEEN 1 AND 120),
  details     jsonb NOT NULL DEFAULT '{}'::jsonb,
  prev_hash   bytea NOT NULL CHECK (octet_length(prev_hash) = 32),
  row_hash    bytea NOT NULL CHECK (octet_length(row_hash) = 32)
);
CREATE INDEX audit_log_entity_idx ON fp.audit_log(entity_type, entity_id);

CREATE TABLE fp.audit_chain_head (
  id       boolean PRIMARY KEY DEFAULT true CHECK (id),
  seq      bigint NOT NULL,
  row_hash bytea NOT NULL
);
INSERT INTO fp.audit_chain_head VALUES (true, 0, sha256(convert_to('fingerpay-audit-genesis-v1', 'UTF8')));

CREATE UNLOGGED TABLE fp.rate_limits (
  bucket       text NOT NULL CHECK (length(bucket) BETWEEN 1 AND 200),
  window_start timestamptz NOT NULL,
  hits         integer NOT NULL CHECK (hits > 0),
  PRIMARY KEY (bucket, window_start)
);

-- ── Row-level security: on for every table, with no policies. No role except the owner can
-- read or write rows directly; all access goes through SECURITY DEFINER functions.
DO $$ DECLARE t text; BEGIN
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'fp' LOOP
    EXECUTE format('ALTER TABLE fp.%I ENABLE ROW LEVEL SECURITY', t);
  END LOOP;
END $$;

-- ── Privileges: strip everything, from everyone, explicitly. ───────────────────────────────
DO $$ DECLARE r text; BEGIN
  REVOKE ALL ON ALL TABLES IN SCHEMA fp FROM PUBLIC;
  REVOKE ALL ON ALL SEQUENCES IN SCHEMA fp FROM PUBLIC;
  FOREACH r IN ARRAY ARRAY['anon','authenticated','service_role','fp_app'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
      EXECUTE format('REVOKE ALL ON SCHEMA fp FROM %I', r);
      EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA fp FROM %I', r);
      EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA fp FROM %I', r);
    END IF;
  END LOOP;
  GRANT USAGE ON SCHEMA fp TO fp_app;
END $$;

COMMIT;
