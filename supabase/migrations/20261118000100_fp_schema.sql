-- FingerPay 1/3: private schema, roles, tables, constraints, row-level security.
--
-- Security model (docs/SPEC.md §4):
--   * Every FingerPay table lives in the private schema `fp`. It is never added to Supabase's
--     exposed Data API schemas, and anon / authenticated / service_role get no rights on it,
--     so a leaked anon or service_role key cannot read or move money.
--   * The Next.js server connects as `fp_app`, which may only EXECUTE the vetted API functions
--     in 20261118000300_fp_api.sql. It has no table privileges at all.
--   * Money changes only through fp.post_journal (double-entry, append-only, audited).
BEGIN;
SET LOCAL lock_timeout = '5s';

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'fp_app') THEN
    -- LOGIN and the password are set once, out of band (docs/SPEC.md §9.2). Never in git.
    CREATE ROLE fp_app NOLOGIN NOINHERIT;
  END IF;
END $$;
-- A stuck or abusive request must never hold ledger locks for long.
ALTER ROLE fp_app SET statement_timeout = '5s';
ALTER ROLE fp_app SET lock_timeout = '3s';
ALTER ROLE fp_app SET idle_in_transaction_session_timeout = '15s';

CREATE SCHEMA fp;
REVOKE ALL ON SCHEMA fp FROM PUBLIC;
GRANT USAGE ON SCHEMA fp TO fp_app;

-- ── Merchants & staff ──────────────────────────────────────────────────────────────────────
CREATE TABLE fp.merchants (
  merchant_id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  store_name             text NOT NULL CHECK (length(btrim(store_name)) BETWEEN 2 AND 120),
  owner_display_name     text NOT NULL CHECK (length(btrim(owner_display_name)) BETWEEN 2 AND 120),
  location               text NOT NULL CHECK (length(btrim(location)) BETWEEN 2 AND 120),
  status                 text NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','SUSPENDED','CLOSED')),
  terminal_trial_ends_at timestamptz NOT NULL DEFAULT now() + interval '90 days',
  created_at             timestamptz NOT NULL DEFAULT now()
);

-- One row per Supabase Auth user who may use FingerPay. Sign-ups are disabled in Supabase Auth;
-- staff accounts are created by an administrator only.
CREATE TABLE fp.staff (
  auth_user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE RESTRICT,
  display_name text NOT NULL CHECK (length(btrim(display_name)) BETWEEN 2 AND 120),
  role         text NOT NULL CHECK (role IN ('BRANCH_OFFICER','BRANCH_MANAGER','MERCHANT_OWNER',
                                             'MERCHANT_CASHIER','BANK_ADMIN','AUDITOR')),
  merchant_id  uuid REFERENCES fp.merchants,
  status       text NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','DISABLED')),
  created_at   timestamptz NOT NULL DEFAULT now(),
  CHECK ((role IN ('MERCHANT_OWNER','MERCHANT_CASHIER')) = (merchant_id IS NOT NULL))
);
CREATE INDEX staff_merchant_idx ON fp.staff(merchant_id);

-- ── Customers (shoppers) ───────────────────────────────────────────────────────────────────
-- *_enc columns hold AES-256-GCM blobs made by the server: 0x01 | key version (2 bytes) |
-- nonce (12) | ciphertext | tag (16). The keys never enter the database.
-- *_idx / thumb_lookup hold HMAC-SHA256 values (32 bytes) keyed by server-side secrets, so a
-- database dump alone can neither reverse them nor replay them as a "thumb".
CREATE TABLE fp.customers (
  customer_id        uuid PRIMARY KEY,  -- generated by the server: it is part of the encryption AAD
  display_name       text NOT NULL CHECK (length(btrim(display_name)) BETWEEN 2 AND 60),  -- 'Ayesha K.'
  full_name_enc      bytea NOT NULL CHECK (octet_length(full_name_enc) BETWEEN 32 AND 2048 AND get_byte(full_name_enc, 0) = 1),
  cnic_enc           bytea NOT NULL CHECK (octet_length(cnic_enc) BETWEEN 32 AND 2048 AND get_byte(cnic_enc, 0) = 1),
  cnic_idx           bytea NOT NULL UNIQUE CHECK (octet_length(cnic_idx) = 32),
  cnic_last4         text  NOT NULL CHECK (cnic_last4 ~ '^[0-9]{4}$'),
  phone_enc          bytea NOT NULL CHECK (octet_length(phone_enc) BETWEEN 32 AND 2048 AND get_byte(phone_enc, 0) = 1),
  phone_last4        text  NOT NULL CHECK (phone_last4 ~ '^[0-9]{4}$'),
  account_type       text  NOT NULL CHECK (account_type IN ('SHOPPER_SALARY','STUDENT_NON_PTA')),
  status             text  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','FROZEN','CLOSED')),
  thumb_lookup       bytea NOT NULL UNIQUE CHECK (octet_length(thumb_lookup) = 32),
  thumb_key_version  smallint NOT NULL CHECK (thumb_key_version > 0),
  thumb_locked       boolean NOT NULL DEFAULT false,  -- shopper-controlled "Thumb Lock"
  first_payment_at   timestamptz,
  referral_code      text UNIQUE CHECK (referral_code ~ '^[A-Z0-9-]{6,20}$'),
  referred_by        uuid REFERENCES fp.customers,
  nadra_ref          text NOT NULL CHECK (length(nadra_ref) BETWEEN 6 AND 64),
  nadra_verified_at  timestamptz NOT NULL,
  consent_version    text NOT NULL CHECK (length(consent_version) BETWEEN 1 AND 32),
  consented_at       timestamptz NOT NULL,
  enrolled_by        uuid NOT NULL REFERENCES fp.staff,
  created_at         timestamptz NOT NULL DEFAULT now(),
  CHECK (referred_by IS DISTINCT FROM customer_id),
  CHECK (referral_code IS NULL OR account_type = 'STUDENT_NON_PTA')
);

-- ── Simulated Allied Bank accounts + double-entry ledger ───────────────────────────────────
CREATE TABLE fp.accounts (
  account_id       uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  kind             text NOT NULL CHECK (kind IN ('CUSTOMER_CASA','MERCHANT_CASA','FP_FEE_INCOME',
                                                 'BANK_FEE_INCOME','MARKETING_POOL','OPENING_EQUITY')),
  customer_id      uuid UNIQUE REFERENCES fp.customers,
  merchant_id      uuid UNIQUE REFERENCES fp.merchants,
  account_no_enc   bytea CHECK (account_no_enc IS NULL OR (octet_length(account_no_enc) BETWEEN 32 AND 2048 AND get_byte(account_no_enc, 0) = 1)),
  account_no_idx   bytea UNIQUE CHECK (account_no_idx IS NULL OR octet_length(account_no_idx) = 32),
  account_no_last4 text CHECK (account_no_last4 ~ '^[0-9]{4}$'),
  balance          numeric(12,2) NOT NULL DEFAULT 0,
  allow_negative   boolean NOT NULL DEFAULT false,
  status           text NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','FROZEN','CLOSED')),
  created_at       timestamptz NOT NULL DEFAULT now(),
  CHECK (allow_negative OR balance >= 0),
  CHECK (allow_negative = (kind = 'OPENING_EQUITY')),
  CHECK ((account_no_enc IS NULL) = (account_no_idx IS NULL)
     AND (account_no_idx IS NULL) = (account_no_last4 IS NULL)),
  CHECK (CASE kind
    WHEN 'CUSTOMER_CASA' THEN customer_id IS NOT NULL AND merchant_id IS NULL AND account_no_idx IS NOT NULL
    WHEN 'MERCHANT_CASA' THEN merchant_id IS NOT NULL AND customer_id IS NULL AND account_no_idx IS NOT NULL
    ELSE customer_id IS NULL AND merchant_id IS NULL AND account_no_idx IS NULL END)
);
CREATE UNIQUE INDEX accounts_one_per_system_kind ON fp.accounts(kind)
  WHERE kind IN ('FP_FEE_INCOME','BANK_FEE_INCOME','MARKETING_POOL','OPENING_EQUITY');

INSERT INTO fp.accounts(kind, allow_negative) VALUES
  ('FP_FEE_INCOME', false), ('BANK_FEE_INCOME', false), ('MARKETING_POOL', false), ('OPENING_EQUITY', true);

CREATE TABLE fp.journals (
  journal_id      uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  kind            text NOT NULL CHECK (kind IN ('PAYMENT','VOID','REFUND','OPENING_BALANCE','POOL_FUNDING',
                                                'MERCHANT_REBATE','REFERRAL_BONUS')),
  idempotency_key text NOT NULL UNIQUE CHECK (length(idempotency_key) BETWEEN 8 AND 200),
  payload_sha256  bytea NOT NULL CHECK (octet_length(payload_sha256) = 32),
  memo            text NOT NULL DEFAULT '' CHECK (length(memo) <= 500),
  actor           text NOT NULL CHECK (length(actor) BETWEEN 1 AND 120),
  created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE fp.journal_entries (
  entry_id      bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  journal_id    uuid NOT NULL REFERENCES fp.journals,
  account_id    uuid NOT NULL REFERENCES fp.accounts,
  amount        numeric(12,2) NOT NULL CHECK (amount <> 0),  -- + credits the account, - debits it
  balance_after numeric(12,2) NOT NULL,
  created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX journal_entries_journal_idx ON fp.journal_entries(journal_id);
CREATE INDEX journal_entries_account_idx ON fp.journal_entries(account_id, entry_id);

-- ── Terminals & signed-request replay protection ───────────────────────────────────────────
CREATE TABLE fp.terminals (
  terminal_id     uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  merchant_id     uuid NOT NULL REFERENCES fp.merchants,
  label           text NOT NULL CHECK (length(btrim(label)) BETWEEN 1 AND 60),
  -- ECDSA P-256 public key, SubjectPublicKeyInfo DER (always 91 bytes, uncompressed point).
  public_key_spki bytea NOT NULL UNIQUE CHECK (octet_length(public_key_spki) = 91),
  status          text NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','REVOKED')),
  paired_by       uuid NOT NULL REFERENCES fp.staff,
  paired_at       timestamptz NOT NULL DEFAULT now(),
  revoked_at      timestamptz,
  last_seen_at    timestamptz,
  CHECK ((status = 'REVOKED') = (revoked_at IS NOT NULL))
);
CREATE INDEX terminals_merchant_idx ON fp.terminals(merchant_id);

CREATE TABLE fp.request_nonces (
  terminal_id uuid NOT NULL REFERENCES fp.terminals,
  nonce       bytea NOT NULL CHECK (octet_length(nonce) BETWEEN 16 AND 32),
  seen_at     timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (terminal_id, nonce)
);
CREATE INDEX request_nonces_seen_idx ON fp.request_nonces(seen_at);

-- ── Charges, attempts, reversals, disputes ─────────────────────────────────────────────────
CREATE TABLE fp.charge_sessions (
  charge_id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  terminal_id       uuid NOT NULL REFERENCES fp.terminals,
  merchant_id       uuid NOT NULL REFERENCES fp.merchants,
  amount            numeric(12,2) NOT NULL CHECK (amount > 0),
  status            text NOT NULL DEFAULT 'AWAITING_THUMB'
                    CHECK (status IN ('AWAITING_THUMB','COMPLETED','CANCELLED','EXPIRED','LOCKED')),
  opened_by         uuid NOT NULL REFERENCES fp.staff,
  thumb_attempts    smallint NOT NULL DEFAULT 0 CHECK (thumb_attempts BETWEEN 0 AND 3),
  result_attempt_id uuid,
  created_at        timestamptz NOT NULL DEFAULT now(),
  expires_at        timestamptz NOT NULL DEFAULT now() + interval '120 seconds',
  closed_at         timestamptz,
  CHECK ((status = 'AWAITING_THUMB') = (closed_at IS NULL)),
  CHECK ((status = 'COMPLETED') = (result_attempt_id IS NOT NULL))
);
CREATE UNIQUE INDEX charge_sessions_one_open_per_terminal ON fp.charge_sessions(terminal_id)
  WHERE status = 'AWAITING_THUMB';

CREATE TABLE fp.payment_attempts (
  attempt_id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  charge_id           uuid REFERENCES fp.charge_sessions,
  terminal_id         uuid NOT NULL REFERENCES fp.terminals,
  merchant_id         uuid NOT NULL REFERENCES fp.merchants,
  customer_id         uuid REFERENCES fp.customers,
  amount              numeric(12,2) NOT NULL CHECK (amount > 0),
  outcome             text NOT NULL CHECK (outcome IN (
                        'SUCCESS','DECLINED_LOW_BALANCE','DECLINED_UNREGISTERED_THUMB','DECLINED_DUPLICATE_TAP',
                        'DECLINED_LIMIT','DECLINED_THUMB_LOCKED','DECLINED_ACCOUNT_INACTIVE',
                        'DECLINED_TERMINAL_THROTTLED','OFFLINE_CASH_FALLBACK')),
  mdr_fee             numeric(12,2) NOT NULL DEFAULT 0 CHECK (mdr_fee >= 0),
  fp_revenue          numeric(12,2) NOT NULL DEFAULT 0 CHECK (fp_revenue >= 0),
  bank_revenue        numeric(12,2) NOT NULL DEFAULT 0 CHECK (bank_revenue >= 0),
  net_to_merchant     numeric(12,2) NOT NULL DEFAULT 0 CHECK (net_to_merchant >= 0),
  cashback            numeric(12,2) NOT NULL DEFAULT 0 CHECK (cashback >= 0),
  raast_ref           text UNIQUE,
  journal_id          uuid UNIQUE REFERENCES fp.journals,
  referral_journal_id uuid UNIQUE REFERENCES fp.journals,
  recorded_by         uuid REFERENCES fp.staff,
  processing_ms       integer CHECK (processing_ms >= 0),
  occurred_at         timestamptz NOT NULL DEFAULT now(),
  created_at          timestamptz NOT NULL DEFAULT now(),
  -- Spec rule: a decline never costs the shopper or merchant anything.
  CHECK (CASE WHEN outcome = 'SUCCESS' THEN
           customer_id IS NOT NULL AND charge_id IS NOT NULL AND raast_ref IS NOT NULL AND journal_id IS NOT NULL
           AND fp_revenue + bank_revenue = mdr_fee AND net_to_merchant = amount - mdr_fee
         ELSE mdr_fee = 0 AND fp_revenue = 0 AND bank_revenue = 0 AND net_to_merchant = 0 AND cashback = 0
           AND raast_ref IS NULL AND journal_id IS NULL AND referral_journal_id IS NULL END),
  CHECK ((outcome = 'OFFLINE_CASH_FALLBACK') = (charge_id IS NULL)),
  CHECK ((outcome = 'OFFLINE_CASH_FALLBACK') = (recorded_by IS NOT NULL))
);
CREATE INDEX payment_attempts_merchant_idx ON fp.payment_attempts(merchant_id, occurred_at);
CREATE INDEX payment_attempts_customer_idx ON fp.payment_attempts(customer_id, created_at) WHERE customer_id IS NOT NULL;
CREATE INDEX payment_attempts_terminal_idx ON fp.payment_attempts(terminal_id, created_at);
ALTER TABLE fp.charge_sessions
  ADD CONSTRAINT charge_sessions_result_fk FOREIGN KEY (result_attempt_id) REFERENCES fp.payment_attempts;

CREATE TABLE fp.disputes (
  dispute_id   uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tracking_ref text NOT NULL UNIQUE,
  attempt_id   uuid NOT NULL REFERENCES fp.payment_attempts,
  customer_id  uuid NOT NULL REFERENCES fp.customers,
  channel      text NOT NULL CHECK (channel IN ('SMS_REPLY','BRANCH')),
  reason       text NOT NULL CHECK (length(btrim(reason)) BETWEEN 3 AND 255),
  status       text NOT NULL DEFAULT 'OPEN_WITH_ALLIED_BANK'
               CHECK (status IN ('OPEN_WITH_ALLIED_BANK','REFUND_PENDING_APPROVAL','RESOLVED_REFUNDED','RESOLVED_REJECTED')),
  raised_by    uuid REFERENCES fp.staff,
  created_at   timestamptz NOT NULL DEFAULT now(),
  resolved_at  timestamptz,
  CHECK ((channel = 'BRANCH') = (raised_by IS NOT NULL)),
  CHECK ((status LIKE 'RESOLVED_%') = (resolved_at IS NOT NULL))
);
CREATE UNIQUE INDEX disputes_one_open_per_attempt ON fp.disputes(attempt_id)
  WHERE status IN ('OPEN_WITH_ALLIED_BANK','REFUND_PENDING_APPROVAL');

-- Same-day voids (merchant owner) post at once. Refunds need a second person (maker-checker).
CREATE TABLE fp.reversals (
  reversal_id  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  attempt_id   uuid NOT NULL REFERENCES fp.payment_attempts,
  kind         text NOT NULL CHECK (kind IN ('VOID','REFUND')),
  dispute_id   uuid REFERENCES fp.disputes,
  reason       text NOT NULL CHECK (length(btrim(reason)) BETWEEN 3 AND 500),
  status       text NOT NULL CHECK (status IN ('PENDING_APPROVAL','POSTED','REJECTED')),
  requested_by uuid NOT NULL REFERENCES fp.staff,
  requested_at timestamptz NOT NULL DEFAULT now(),
  decided_by   uuid REFERENCES fp.staff,
  decided_at   timestamptz,
  journal_id   uuid UNIQUE REFERENCES fp.journals,
  CHECK (kind = 'VOID' OR decided_by IS NULL OR decided_by <> requested_by),
  CHECK (kind = 'REFUND' OR status = 'POSTED'),
  CHECK ((kind = 'REFUND') = (dispute_id IS NOT NULL)),
  CHECK ((status = 'POSTED') = (journal_id IS NOT NULL)),
  CHECK ((status = 'PENDING_APPROVAL') = (decided_at IS NULL)),
  CHECK ((decided_at IS NULL) = (decided_by IS NULL))
);
CREATE UNIQUE INDEX reversals_one_live_per_attempt ON fp.reversals(attempt_id) WHERE status <> 'REJECTED';

-- ── SMS outbox, limits, stats ──────────────────────────────────────────────────────────────
CREATE TABLE fp.sms_outbox (
  sms_id      uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  customer_id uuid NOT NULL REFERENCES fp.customers,
  attempt_id  uuid REFERENCES fp.payment_attempts,
  kind        text NOT NULL CHECK (kind IN ('PAYMENT_RECEIPT','DECLINE_NOTICE','SECURITY_ALERT','ENROLLMENT',
                                            'DISPUTE_RAISED','THUMB_LOCK','REFUND','VOID','REFERRAL_BONUS')),
  body        text NOT NULL CHECK (length(body) BETWEEN 1 AND 480),
  created_at  timestamptz NOT NULL DEFAULT clock_timestamp(),
  sent_at     timestamptz
);
CREATE INDEX sms_outbox_created_idx ON fp.sms_outbox(created_at DESC);

CREATE TABLE fp.account_limits (
  account_type     text PRIMARY KEY CHECK (account_type IN ('SHOPPER_SALARY','STUDENT_NON_PTA')),
  per_tap_max      numeric(12,2) NOT NULL CHECK (per_tap_max > 0),
  daily_amount_max numeric(12,2) NOT NULL CHECK (daily_amount_max >= per_tap_max),
  daily_count_max  integer NOT NULL CHECK (daily_count_max > 0),
  updated_at       timestamptz NOT NULL DEFAULT now()
);
