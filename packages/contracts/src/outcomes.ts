/**
 * Payment outcome codes returned by the API. The UI maps codes to text (never the server),
 * so Urdu can be added by adding a second banner map.
 */
export const OUTCOME_CODES = [
  'SUCCESS',
  'DECLINED_LOW_BALANCE',
  'DECLINED_UNREGISTERED_THUMB',
  'DECLINED_DUPLICATE_TAP',
  'DECLINED_LIMIT',
  'DECLINED_THUMB_LOCKED',
  'DECLINED_ACCOUNT_INACTIVE',
  'DECLINED_TERMINAL_THROTTLED',
  'DECLINED_SETTLEMENT_UNAVAILABLE',
  'CHARGE_LOCKED',
  'CHARGE_EXPIRED',
  'CHARGE_CANCELLED',
] as const;

export type OutcomeCode = (typeof OUTCOME_CODES)[number];

/** Client-side only outcome: the terminal is offline and never sent anything. */
export type ClientOutcome = OutcomeCode | 'OFFLINE';

export const BANNERS_EN: Record<ClientOutcome, (p: { amount?: string }) => string> = {
  SUCCESS: ({ amount }) => `PAYMENT SUCCESSFUL — PKR ${amount ?? ''} RECEIVED`,
  DECLINED_LOW_BALANCE: () => 'PAYMENT DECLINED: INSUFFICIENT BALANCE (PKR 0 FEE CHARGED)',
  DECLINED_UNREGISTERED_THUMB: () => 'THUMB NOT RECOGNIZED — ENROL AT YOUR BANK BRANCH',
  DECLINED_DUPLICATE_TAP: () => 'DUPLICATE TAP BLOCKED — THIS SALE WAS ALREADY PAID',
  DECLINED_LIMIT: () => 'PAYMENT DECLINED: ABOVE THUMB-PAY LIMIT (PKR 0 FEE CHARGED)',
  DECLINED_THUMB_LOCKED: () => 'PAYMENT DECLINED: THUMB PAYMENTS ARE LOCKED BY THE OWNER',
  DECLINED_ACCOUNT_INACTIVE: () => 'PAYMENT DECLINED: ACCOUNT NOT ACTIVE',
  DECLINED_TERMINAL_THROTTLED: () => 'TOO MANY UNKNOWN THUMBS — TERMINAL PAUSED FOR 10 MINUTES',
  DECLINED_SETTLEMENT_UNAVAILABLE: () =>
    'PAYMENT DECLINED: RECEIVING BANK UNAVAILABLE (PKR 0 FEE CHARGED)',
  CHARGE_LOCKED: () => 'START A NEW SALE',
  CHARGE_EXPIRED: () => 'START A NEW SALE',
  CHARGE_CANCELLED: () => 'START A NEW SALE',
  OFFLINE: () => 'INTERNET DOWN — TAKE CASH IMMEDIATELY (SALE NOT CHARGED)',
};
